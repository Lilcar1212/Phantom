local function buildHarbour()
	local f = folders.Harbour
	for _, p in ipairs(DATA.piers) do
		local cf0 = CFrame.new(W(p.x0 + p.length / 2, p.y, 4))
		if not placeAsset("HO_Harbour_Pier", CFrame.new(W(p.x0, p.y, 0)) * CFrame.Angles(0, FACING.E, 0), f) then
			part(f, Vector3.new(p.length, 0.6, p.width), cf0 * CFrame.new(0, -0.3, 0), COL.wood, Enum.Material.WoodPlanks, p.label)
			part(f, Vector3.new(16, 0.6, p.width + 16), CFrame.new(W(p.x0 + p.length - 8, p.y, 3.7)), COL.wood, Enum.Material.WoodPlanks, "PierHead")
			for x = p.x0 + 4, p.x0 + p.length, 8 do
				for _, s in ipairs({ -1, 1 }) do
					part(f, Vector3.new(1, 1, 16), CFrame.new(W(x, p.y + s * (p.width / 2 - 0.5), -4)) * CFrame.Angles(math.rad(90), 0, 0),
						COL.timber, Enum.Material.Wood, "Post", Enum.PartType.Cylinder)
				end
			end
		end
	end
	-- promenade paving + quay edge
	part(f, Vector3.new(40, 0.2, 740), CFrame.new(W(752, 410, 4.1)), COL.cobble, Enum.Material.Cobblestone, "Promenade")
	part(f, Vector3.new(2, 1, 780), CFrame.new(W(771, 430, 4.5)), COL.stone, Enum.Material.Slate, "QuayCap")
	-- arched bridge over the canal
	local b = DATA.bridge
	if not placeAsset("HO_Harbour_ArchBridge", CFrame.new(W(b.c[1], b.c[2], 4)), f) then
		local n = 12
		for i = 0, n - 1 do
			local t0, t1 = i / n, (i + 1) / n
			local y0 = b.c[2] - b.size[2] / 2 + b.size[2] * t0
			local y1 = b.c[2] - b.size[2] / 2 + b.size[2] * t1
			local z0 = 4 + 6 * math.sin(math.pi * t0)
			local z1 = 4 + 6 * math.sin(math.pi * t1)
			local p0, p1 = W(b.c[1], y0, z0), W(b.c[1], y1, z1)
			local cf = CFrame.lookAt((p0 + p1) / 2, p1)
			part(f, Vector3.new(b.size[1], 0.8, (p1 - p0).Magnitude + 0.1), cf, COL.wood, Enum.Material.WoodPlanks, "BridgeDeck")
			for _, s in ipairs({ -1, 1 }) do
				part(f, Vector3.new(0.5, 0.4, (p1 - p0).Magnitude + 0.1), cf * CFrame.new(s * (b.size[1] / 2 - 0.3), 3.2, 0), COL.red, Enum.Material.SmoothPlastic, "Rail")
				part(f, Vector3.new(0.4, 3, 0.4), cf * CFrame.new(s * (b.size[1] / 2 - 0.3), 1.6, 0), COL.red, Enum.Material.SmoothPlastic, "Baluster")
			end
		end
	end
	-- causeway to the lighthouse rock
	for i = 1, #DATA.causeway - 1 do
		local a, c = DATA.causeway[i], DATA.causeway[i + 1]
		local p0, p1 = W(a[1], a[2], 3), W(c[1], c[2], 3)
		part(f, Vector3.new(12, 6, (p1 - p0).Magnitude + 6), CFrame.lookAt((p0 + p1) / 2, p1) * CFrame.new(0, -2, 0), COL.stone, Enum.Material.Slate, "Causeway")
	end
	-- lighthouse
	local lh = W(856, 904, 12)
	if not placeAsset("HO_Harbour_Lighthouse", CFrame.new(lh), f) then
		part(f, Vector3.new(28, 12, 12), CFrame.new(lh + Vector3.new(0, 14, 0)) * CFrame.Angles(0, 0, math.rad(90)), COL.plaster, Enum.Material.SmoothPlastic, "Tower", Enum.PartType.Cylinder)
		local lamp = part(f, Vector3.new(6, 8, 8), CFrame.new(lh + Vector3.new(0, 31, 0)) * CFrame.Angles(0, 0, math.rad(90)), Color3.fromRGB(255, 214, 140), Enum.Material.Neon, "Lantern", Enum.PartType.Cylinder)
		local pl = Instance.new("PointLight"); pl.Range = 60; pl.Brightness = 3; pl.Color = Color3.fromRGB(255, 200, 120); pl.Parent = lamp
		wedge(f, Vector3.new(12, 5, 6), CFrame.new(lh + Vector3.new(0, 37.5, 3)), COL.roof, "Roof")
		wedge(f, Vector3.new(12, 5, 6), CFrame.new(lh + Vector3.new(0, 37.5, -3)) * CFrame.Angles(0, math.pi, 0), COL.roof, "Roof")
	end
end

local function torii(parent, x, y, facing)
	local e = elevAt(x, y)
	local cf = CFrame.new(W(x, y, e)) * CFrame.Angles(0, (facing == "E" or facing == "W") and math.rad(90) or 0, 0)
	if placeAsset("HO_Prop_Torii", cf, parent) then return end
	local m = Instance.new("Model"); m.Name = "Torii_Placeholder"; m.Parent = parent
	for _, s in ipairs({ -1, 1 }) do
		part(m, Vector3.new(11, 1.3, 1.3), cf * CFrame.new(s * 4.5, 5.5, 0) * CFrame.Angles(0, 0, math.rad(90)), COL.red, Enum.Material.SmoothPlastic, "Pillar", Enum.PartType.Cylinder)
	end
	part(m, Vector3.new(14, 1, 1.6), cf * CFrame.new(0, 11.3, 0), Color3.fromRGB(30, 26, 24), Enum.Material.SmoothPlastic, "Kasagi")
	part(m, Vector3.new(13, 0.8, 1.3), cf * CFrame.new(0, 10.5, 0), COL.red, Enum.Material.SmoothPlastic, "Shimaki")
	part(m, Vector3.new(11.5, 0.7, 0.8), cf * CFrame.new(0, 8.8, 0), COL.red, Enum.Material.SmoothPlastic, "Nuki")
end

local function buildProps()
	for _, t in ipairs(DATA.torii) do torii(folders.Props, t.c[1], t.c[2], t.facing) end
	for _, wl in ipairs(DATA.wells) do
		local p = W(wl[1], wl[2], elevAt(wl[1], wl[2]))
		if not placeAsset("HO_Prop_Well", CFrame.new(p), folders.Props) then
			part(folders.Props, Vector3.new(2.5, 5, 5), CFrame.new(p + Vector3.new(0, 1.25, 0)) * CFrame.Angles(0, 0, math.rad(90)), COL.stone, Enum.Material.Slate, "Well", Enum.PartType.Cylinder)
		end
	end
end

local function buildTrees()
	local f = folders.Nature
	local S = { S = 0.7, M = 1.0, L = 1.4 }
	for i, t in ipairs(DATA.trees) do
		local e = elevAt(t.x, t.y)
		local p = W(t.x, t.y, e)
		local rot = CFrame.Angles(0, (i * 2.399) % (2 * math.pi), 0)
		if not placeAsset("HO_Tree_Pine_" .. t.size, CFrame.new(p) * rot, f) then
			local s = S[t.size] or 1
			local m = Instance.new("Model"); m.Name = "Pine_Placeholder"; m.Parent = f
			part(m, Vector3.new(10 * s, 1.2 * s, 1.2 * s), CFrame.new(p + Vector3.new(0, 5 * s, 0)) * CFrame.Angles(0, 0, math.rad(90)), COL.bark, Enum.Material.Wood, "Trunk", Enum.PartType.Cylinder)
			for k, h in ipairs({ 6, 8.5, 10.5 }) do
				local r = (9 - k * 2) * s
				part(m, Vector3.new(2.2 * s, r, r), CFrame.new(p + Vector3.new((k - 2) * 1.2 * s, h * s, 0)) * rot * CFrame.Angles(0, 0, math.rad(90)),
					COL.pine, Enum.Material.Grass, "Foliage", Enum.PartType.Cylinder)
			end
		end
	end
end

