local function W(x, y, e)
	return Vector3.new(x - 450, e or 0, 600 - y)
end

local function part(parent, size, cf, color, material, name, shape)
	local p = Instance.new("Part")
	p.Anchored = true
	p.Size = size
	p.CFrame = cf
	p.Color = color
	p.Material = material or Enum.Material.SmoothPlastic
	p.TopSurface = Enum.SurfaceType.Smooth
	p.BottomSurface = Enum.SurfaceType.Smooth
	if shape then p.Shape = shape end
	p.Name = name or "Part"
	p.Parent = parent
	return p
end

local function wedge(parent, size, cf, color, name)
	local p = Instance.new("WedgePart")
	p.Anchored = true
	p.Size = size
	p.CFrame = cf
	p.Color = color
	p.Material = Enum.Material.Slate
	p.Name = name or "Wedge"
	p.Parent = parent
	return p
end

local function pointInPoly(x, y, poly)
	local inside = false
	local j = #poly
	for i = 1, #poly do
		local xi, yi = poly[i][1], poly[i][2]
		local xj, yj = poly[j][1], poly[j][2]
		if ((yi > y) ~= (yj > y)) and (x < (xj - xi) * (y - yi) / (yj - yi) + xi) then
			inside = not inside
		end
		j = i
	end
	return inside
end

local function elevAt(x, y)
	local best = 0
	for _, t in ipairs(DATA.tiers) do
		if t.elev > best and pointInPoly(x, y, t.poly) then best = t.elev end
	end
	return best
end

-- vertical scanline fill of a plan polygon with terrain between heights h0..h1
local function fillPoly(poly, h0, h1, material, step)
	step = step or 4
	local xmin, xmax = math.huge, -math.huge
	for _, p in ipairs(poly) do
		xmin = math.min(xmin, p[1]); xmax = math.max(xmax, p[1])
	end
	local x = math.floor(xmin / step) * step
	while x < xmax do
		local xc = x + step / 2
		local ys = {}
		local j = #poly
		for i = 1, #poly do
			local x1, y1 = poly[j][1], poly[j][2]
			local x2, y2 = poly[i][1], poly[i][2]
			if (x1 <= xc and x2 > xc) or (x2 <= xc and x1 > xc) then
				table.insert(ys, y1 + (xc - x1) / (x2 - x1) * (y2 - y1))
			end
			j = i
		end
		table.sort(ys)
		for k = 1, #ys - 1, 2 do
			local ya, yb = ys[k], ys[k + 1]
			if yb - ya > 0.5 then
				local c = W(xc, (ya + yb) / 2, (h0 + h1) / 2)
				Terrain:FillBlock(CFrame.new(c), Vector3.new(step, h1 - h0, yb - ya), material)
			end
		end
		x = x + step
	end
end

-- find an imported asset template by name (anywhere under ServerStorage.HO_Assets)
local function asset(name)
	local lib = ServerStorage:FindFirstChild("HO_Assets")
	if not lib then return nil end
	return lib:FindFirstChild(name, true)
end

-- place a clone so that the asset's own origin (footprint centre / bottom centre) lands on `cf`
local function placeAsset(name, cf, parent)
	local tpl = asset(name)
	if not tpl then return nil end
	local m = tpl:Clone()
	if m:IsA("BasePart") then
		local g = Instance.new("Model"); g.Name = name; m.Parent = g; m = g
	end
	local b = BOUNDS[name]
	local bcf, bsize = m:GetBoundingBox()
	if b then
		-- bbox centre in asset space -> the model's origin in world space (template assumed unrotated)
		local origin = bcf.Position - Vector3.new(b.c[1], b.c[2], b.c[3])
		m.WorldPivot = CFrame.new(origin)
	else
		m.WorldPivot = CFrame.new(bcf.Position - Vector3.new(0, bsize.Y / 2, 0))
	end
	m:PivotTo(cf)
	for _, d in ipairs(m:GetDescendants()) do
		if d:IsA("BasePart") then d.Anchored = true end
	end
	m.Parent = parent
	return m
end

