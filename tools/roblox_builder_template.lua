-- simple gable roof from two wedges over a w x d footprint (ridge along local X)
local function placeholderRoof(parent, cf, w, d, rise, overhang)
	overhang = overhang or 2
	local hw = d / 2 + overhang
	local L = w + overhang
	wedge(parent, Vector3.new(L, rise, hw), cf * CFrame.new(0, rise / 2, hw / 2), COL.roof, "RoofFront")
	wedge(parent, Vector3.new(L, rise, hw), cf * CFrame.new(0, rise / 2, -hw / 2) * CFrame.Angles(0, math.pi, 0), COL.roof, "RoofBack")
end

local function roofFor(w, d)
	local opts = {
		{ "HO_Roof_Kirizuma_Small", 12, 12 }, { "HO_Roof_Irimoya_Small", 16, 12 }, { "HO_Roof_Kirizuma_Large", 20, 16 },
		{ "HO_Roof_Irimoya_Medium", 24, 16 }, { "HO_Roof_Irimoya_Large", 32, 24 },
	}
	for _, o in ipairs(opts) do
		if o[2] >= w and o[2] <= w + 4 and o[3] >= d and o[3] <= d + 4 then return o[1] end
	end
	return nil
end

-- generic building: real asset if present, else plinth + plaster block (+ real roof asset if imported)
local function building(parent, name, x, y, elev, w, d, facing, storeys, color, text)
	-- w/d are plan (X/Y) extents; the model's own width runs along its front, so swap for E/W facing
	if facing == "E" or facing == "W" then w, d = d, w end
	local cf = CFrame.new(W(x, y, elev)) * CFrame.Angles(0, FACING[facing] or 0, 0)
	if placeAsset(name, cf, parent) then return end
	local m = Instance.new("Model"); m.Name = name .. "_Placeholder"; m.Parent = parent
	local h = 9 * storeys
	part(m, Vector3.new(w + 0.6, 1, d + 0.6), cf * CFrame.new(0, 0.5, 0), COL.stone, Enum.Material.Slate, "Plinth")
	local body = part(m, Vector3.new(w, h, d), cf * CFrame.new(0, 1 + h / 2, 0), color or COL.plaster, Enum.Material.SmoothPlastic, "Walls")
	for i = 0, storeys do
		part(m, Vector3.new(w + 0.2, 0.7, d + 0.2), cf * CFrame.new(0, 1 + 9 * i - (i == storeys and 0.35 or 0), 0), COL.timber, Enum.Material.Wood, "Beam")
	end
	for _, sx in ipairs({ -1, 1 }) do
		for _, sz in ipairs({ -1, 1 }) do
			part(m, Vector3.new(1.3, h, 1.3), cf * CFrame.new(sx * (w / 2 - 0.5), 1 + h / 2, sz * (d / 2 - 0.5)), COL.timber, Enum.Material.Wood, "Post")
		end
	end
	local top = cf * CFrame.new(0, 1 + h, 0)
	local rname = roofFor(w, d)
	if not (rname and placeAsset(rname, top, m)) then
		placeholderRoof(m, top, w, d, math.max(4, d * 0.35), 2)
	end
	if text then label(body, text) end
	m.PrimaryPart = body
end

