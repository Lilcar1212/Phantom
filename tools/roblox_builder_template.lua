local function buildTerrain()
	Terrain:Clear()
	-- open sea / horizon and sea bed
	Terrain:FillBlock(CFrame.new(W(1150, 600, -16)), Vector3.new(900, 8, 2400), Enum.Material.Sand)
	Terrain:FillBlock(CFrame.new(W(1150, 600, -6)), Vector3.new(900, 12, 2400), Enum.Material.Water)
	fillPoly(DATA.sea, -20, -12, Enum.Material.Sand, 8)
	fillPoly(DATA.sea, -12, 0, Enum.Material.Water, 8)
	-- south edge land skirt (below the town) so the map has no hard edge
	Terrain:FillBlock(CFrame.new(W(386, 20, -6)), Vector3.new(772, 28, 40), Enum.Material.Ground)
	-- tiers: slate body (reads as fitted stone retaining walls on the sides) + top layer
	for _, t in ipairs(DATA.tiers) do
		local top = (t.elev >= 46) and Enum.Material.Grass or Enum.Material.Ground
		fillPoly(t.poly, -20, t.elev - 2, Enum.Material.Slate, 4)
		fillPoly(t.poly, t.elev - 2, t.elev, top, 4)
	end
	-- cliffs and mountain behind the castle
	for i, c in ipairs(DATA.cliffs) do
		fillPoly(c, -20, (i == 3) and 50 or 130, Enum.Material.Rock, 4)
	end
	Terrain:FillBlock(CFrame.new(W(450, 1300, 60)), Vector3.new(1400, 160, 200), Enum.Material.Rock)
	-- tidal canal cut into the lower town
	fillPoly(DATA.inlet, -2, 20, Enum.Material.Air, 4)
	fillPoly(DATA.inlet, -12, 0, Enum.Material.Water, 4)
	for _, r in ipairs(DATA.rocks) do
		Terrain:FillBall(W(r.c[1], r.c[2], 2), r.r * 0.8, Enum.Material.Rock)
		Terrain:FillBall(W(r.c[1], r.c[2], -8), r.r, Enum.Material.Rock)
	end
end

local function buildStreets()
	local f = folders.Streets
	for _, s in ipairs(DATA.streets) do
		local mat = (s.kind == "alley") and Enum.Material.Ground or Enum.Material.Cobblestone
		local col = (s.kind == "alley") and COL.dirt or COL.cobble
		for i = 1, #s.path - 1 do
			local a, b = s.path[i], s.path[i + 1]
			local dx, dy = b[1] - a[1], b[2] - a[2]
			local len = math.sqrt(dx * dx + dy * dy)
			local n = math.max(1, math.floor(len / 8 + 0.5))
			for k = 0, n - 1 do
				local t0, t1 = k / n, (k + 1) / n
				local x0, y0 = a[1] + dx * t0, a[2] + dy * t0
				local x1, y1 = a[1] + dx * t1, a[2] + dy * t1
				local xc, yc = (x0 + x1) / 2, (y0 + y1) / 2
				local e = elevAt(xc, yc)
				local p0, p1 = W(x0, y0, e + 0.1), W(x1, y1, e + 0.1)
				local cf = CFrame.lookAt((p0 + p1) / 2, p1)
				part(f, Vector3.new(s.width, 0.2, (p1 - p0).Magnitude + 0.05), cf, col, mat, "Street")
			end
		end
	end
	-- market square paving
	part(f, Vector3.new(84, 0.25, 72), CFrame.new(W(440, 400, 20.12)), Color3.fromRGB(150, 142, 128), Enum.Material.Cobblestone, "MarketSquare")
end

local function buildStairs()
	local f = folders.Streets
	for _, s in ipairs(DATA.stairs) do
		local lo, hi = string.match(s.rise, "(%d+)%D+(%d+)")
		lo, hi = tonumber(lo), tonumber(hi)
		if lo > hi then lo, hi = hi, lo end
		local alongX = s.size[1] >= s.size[2]
		local len = alongX and s.size[1] or s.size[2]
		local wid = alongX and s.size[2] or s.size[1]
		local cx, cy = s.c[1], s.c[2]
		-- which end is high?
		local ax, ay = alongX and 1 or 0, alongX and 0 or 1
		local eA = elevAt(cx - ax * (len / 2 + 6), cy - ay * (len / 2 + 6))
		local eB = elevAt(cx + ax * (len / 2 + 6), cy + ay * (len / 2 + 6))
		local dir = (eB >= eA) and 1 or -1
		local n = math.max(2, hi - lo)
		local depth = len / n
		for k = 1, n do
			local top = lo + (hi - lo) * k / n
			local off = (-len / 2 + depth * (k - 0.5)) * dir
			local px, py = cx + ax * off, cy + ay * off
			local size = alongX and Vector3.new(depth, top - lo + 2, wid) or Vector3.new(wid, top - lo + 2, depth)
			part(f, size, CFrame.new(W(px, py, (top + lo - 2) / 2)), COL.stone, Enum.Material.Slate, "Step")
		end
	end
end

local function buildCastleWalls()
	local f = folders.Castle
	local gates = DATA.gates
	for _, t in ipairs(DATA.tiers) do
		if t.elev >= 46 then
			local poly = t.poly
			for i = 1, #poly do
				local a, b = poly[i], poly[(i % #poly) + 1]
				local dx, dy = b[1] - a[1], b[2] - a[2]
				local len = math.sqrt(dx * dx + dy * dy)
				local n = math.max(1, math.floor(len / 12))
				for k = 0, n - 1 do
					local x0, y0 = a[1] + dx * k / n, a[2] + dy * k / n
					local x1, y1 = a[1] + dx * (k + 1) / n, a[2] + dy * (k + 1) / n
					local xc, yc = (x0 + x1) / 2, (y0 + y1) / 2
					local nearGate = false
					for _, g in ipairs(gates) do
						if math.abs(g.c[1] - xc) < 16 and math.abs(g.c[2] - yc) < 10 then nearGate = true end
					end
					if not nearGate then
						local p0, p1 = W(x0, y0, t.elev), W(x1, y1, t.elev)
						local cf = CFrame.lookAt((p0 + p1) / 2, p1)
						local L = (p1 - p0).Magnitude + 0.6
						part(f, Vector3.new(2, 6, L), cf * CFrame.new(0, 3, 0), COL.plaster, Enum.Material.SmoothPlastic, "CastleWall")
						part(f, Vector3.new(3, 0.8, L + 0.4), cf * CFrame.new(0, 6.4, 0), COL.roof, Enum.Material.Slate, "WallCap")
					end
				end
			end
		end
	end
	for _, g in ipairs(DATA.gates) do
		local e = elevAt(g.c[1], g.c[2] + 8)
		building(folders.Castle, "HO_Castle_Gatehouse", g.c[1], g.c[2], e, 28, 12, "S", 1, COL.timber, g.label)
	end
	for _, y in ipairs(DATA.yagura) do
		local e = elevAt(y[1] + 0.1, y[2] + 0.1)
		for _, t in ipairs(DATA.tiers) do
			if t.elev >= 46 and pointInPoly(y[1] + 2, y[2] + 2, t.poly) then e = math.max(e, t.elev) end
		end
		building(folders.Castle, "HO_Castle_Yagura", y[1], y[2], e, 16, 12, "S", 2, COL.plaster, nil)
	end
end

local function buildKeep(k)
	local f = folders.Castle
	local cf = CFrame.new(W(k.c[1], k.c[2], k.elev)) * CFrame.Angles(0, FACING[k.facing], 0)
	if placeAsset("HO_Castle_Keep", cf, f) then return end
	local m = Instance.new("Model"); m.Name = "HO_Castle_Keep_Placeholder"; m.Parent = f
	local w, d = k.size[1], k.size[2]
	-- battered stone base
	local base = part(m, Vector3.new(w, 16, d), cf * CFrame.new(0, 8, 0), COL.stone, Enum.Material.Slate, "StoneBase")
	local y = 16
	for i = 1, 5 do
		local s = 1 - (i - 1) * 0.16
		local tw, td = w * 0.82 * s, d * 0.82 * s
		part(m, Vector3.new(tw, 9, td), cf * CFrame.new(0, y + 4.5, 0), COL.plaster, Enum.Material.SmoothPlastic, "Tier" .. i)
		part(m, Vector3.new(tw + 5, 1.2, td + 5), cf * CFrame.new(0, y + 9.2, 0), COL.roof, Enum.Material.Slate, "Skirt" .. i)
		y = y + 10
	end
	placeholderRoof(m, cf * CFrame.new(0, y, 0), w * 0.82 * 0.36, d * 0.82 * 0.36, 7, 3)
	for _, sx in ipairs({ -1, 1 }) do
		part(m, Vector3.new(1.2, 3, 2.5), cf * CFrame.new(sx * (w * 0.15 + 1), y + 7.5, 0), COL.gold, Enum.Material.Metal, "Shachihoko")
	end
	label(base, k.label)
end

local function buildKey()
	for _, k in ipairs(DATA.key) do
		if k.id == "keep" then
			buildKeep(k)
		elseif k.kind == "yard" then
			part(folders.Castle, Vector3.new(k.size[1], 0.3, k.size[2]), CFrame.new(W(k.c[1], k.c[2], k.elev + 0.15)),
				Color3.fromRGB(200, 184, 150), Enum.Material.Sand, "TrainingYard")
		elseif k.kind ~= "square" and k.id ~= "lighthouse" then
			local names = { tidewatch_inn = "HO_Bldg_TidewatchInn", blacksmith = "HO_Bldg_Blacksmith", armory = "HO_Bldg_Armory",
				general_store = "HO_Bldg_GeneralStore", magic_stall = "HO_Bldg_MagicStall", academy_hall = "HO_Castle_AcademyHall" }
			local storeys = (k.id == "magic_stall") and 1 or 2
			local col = (k.kind == "special") and COL.special or COL.plaster
			building(folders.Buildings, names[k.id] or ("HO_Bldg_" .. k.id), k.c[1], k.c[2], k.elev, k.size[1], k.size[2],
				k.facing ~= "-" and k.facing or "S", storeys, col, k.label)
		end
	end
end

